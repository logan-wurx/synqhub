// Writes src/lib/brands/asus/devices.generated.ts from ASUS Gear Link device manifests.
//
// Source: https://gearlink.asus.com/hid-whitelist.json lists the supported PIDs (decimal), and each has
// https://gearlink.asus.com/view/<decimalPid>/manifest.json with { pid, version, bundleId, caps }.
// Fetch them with curl into a folder (data only, nothing is executed), then:
//   node scripts/gen-asus-devices.mjs <folder with <pid>.json files> [snapshot date]
// The manifests are read as JSON text; only the fields below are kept.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
const snapshot = process.argv[3] ?? new Date().toISOString().slice(0, 10);
if (!dir) {
  console.error("usage: node scripts/gen-asus-devices.mjs <manifest folder> [snapshot date]");
  process.exit(1);
}

// Gear Link deviceType codes (devices.js enum `o`).
const KIND = { "01": "mouse", "02": "keyboard", "04": "headset", 19: "gamepad", 21: "receiver", 29: "dock" };
const hex4 = (n) => "0x" + n.toString(16).padStart(4, "0");
const q = (s) => JSON.stringify(s);

const rows = [];
for (const f of fs.readdirSync(dir).filter((f) => /^\d+\.json$/.test(f))) {
  const j = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  const c = j.caps ?? {};
  const pid = Number(j.pid);
  if (!Number.isInteger(pid) || pid <= 0 || pid > 0xffff) throw new Error(`${f}: bad pid ${j.pid}`);
  const kind = KIND[c.deviceType];
  if (!kind) throw new Error(`${f}: unknown deviceType ${c.deviceType}`);
  const conn = c.connectionType === "USB" ? "usb" : c.connectionType === "RF_MODE" ? "rf" : null;
  const analog =
    c.isMagneticAxis && typeof c.magKeyUnit === "number"
      ? {
          unitMm: c.magKeyUnit,
          actuation: c.minAP !== undefined ? [c.minAP, c.maxAP] : null,
          rapidTrigger: c.minRT !== undefined ? [c.minRT, c.maxRT] : null,
          deadZone: c.minDZ !== undefined ? [c.minDZ, c.maxDZ] : null,
          defaults: {
            actuation: c.defaultAP,
            rapidTrigger: c.defaultRT,
            rtPress: c.defaultRTPress,
            rtRelease: c.defaultRTRelease,
            dzTop: c.defaultDZTop,
            dzBottom: c.defaultDZBottom,
          },
        }
      : null;
  rows.push({
    pid,
    name: c.deviceName,
    productNumber: c.productNumber,
    kind,
    subtype: c.deviceSubtype ?? null,
    hidPattern: Number(c.hidPattern),
    connection: conn,
    version: j.version,
    bundleId: j.bundleId,
    magnetic: !!c.isMagneticAxis,
    analog,
    firmwareUpdateMethod: c.firmwareUpdateMethod ?? null,
    flags: {
      hasPowerInfo: !!c.hasPowerInfo,
      supportsBooster: !!c.isSupportBooster,
      hasOled: !!c.hasOLED,
      hasHwCopilot: !!c.hasHwCopilot,
    },
  });
}
rows.sort((a, b) => a.pid - b.pid);

const tuple = (t) => (t ? `[${t[0]}, ${t[1]}]` : "null");
const lines = rows.map((r) => {
  const a = r.analog;
  const analog = a
    ? `{ unitMm: ${a.unitMm}, actuation: ${tuple(a.actuation)}, rapidTrigger: ${tuple(a.rapidTrigger)}, deadZone: ${tuple(a.deadZone)}, defaults: { actuation: ${a.defaults.actuation ?? "null"}, rapidTrigger: ${a.defaults.rapidTrigger ?? "null"}, rtPress: ${a.defaults.rtPress ?? "null"}, rtRelease: ${a.defaults.rtRelease ?? "null"}, dzTop: ${a.defaults.dzTop ?? "null"}, dzBottom: ${a.defaults.dzBottom ?? "null"} } }`
    : "null";
  const flags = Object.entries(r.flags)
    .filter(([, v]) => v)
    .map(([k]) => `${k}: true`)
    .join(", ");
  return `  { pid: ${hex4(r.pid)}, name: ${q(r.name)}, productNumber: ${q(r.productNumber)}, kind: ${q(r.kind)}, subtype: ${q(r.subtype)}, hidPattern: ${r.hidPattern}, connection: ${q(r.connection)}, magnetic: ${r.magnetic}, analog: ${analog}, firmwareUpdateMethod: ${q(r.firmwareUpdateMethod)}, bundle: { version: ${q(r.version)}, id: ${q(r.bundleId)} }, flags: {${flags ? " " + flags + " " : ""}} },`;
});

const out = `// GENERATED by scripts/gen-asus-devices.mjs from ASUS Gear Link manifests. Do not edit by hand.
// Sources (public, read as data): https://gearlink.asus.com/hid-whitelist.json (PID list) and
// https://gearlink.asus.com/view/<decimalPid>/manifest.json (caps), snapshot ${snapshot}, ${rows.length} PIDs.
// Fields kept: deviceName, productNumber, deviceType, deviceSubtype, hidPattern, connectionType,
// isMagneticAxis + magKeyUnit + min/max/default AP/RT/DZ (mm), firmwareUpdateMethod, a few feature flags.
// hidPattern 3 marks an alternate (bootloader / updater) PID; see devices.ts for how that is used.

export interface GearLinkAnalogCaps {
  /** Distance unit the firmware counts in, in mm (manifest magKeyUnit): 0.1 on the HFX generation, 0.01 on newer boards. */
  unitMm: number;
  /** [min, max] in mm, or null when the manifest omits it. */
  actuation: readonly [number, number] | null;
  rapidTrigger: readonly [number, number] | null;
  deadZone: readonly [number, number] | null;
  defaults: {
    actuation: number | null;
    rapidTrigger: number | null;
    rtPress: number | null;
    rtRelease: number | null;
    dzTop: number | null;
    dzBottom: number | null;
  };
}

export interface GearLinkDevice {
  pid: number;
  name: string;
  /** ASUS internal model code (p723, m901...). Several PIDs share one. */
  productNumber: string;
  kind: "mouse" | "keyboard" | "headset" | "gamepad" | "receiver" | "dock";
  subtype: string | null;
  /** 1 = normal app collections, 2 = headset layout, 3 = alternate / bootloader PID. */
  hidPattern: number;
  /** "usb" / "rf" when the manifest says; null when it does not. */
  connection: "usb" | "rf" | null;
  magnetic: boolean;
  analog: GearLinkAnalogCaps | null;
  /** "WEB" = Gear Link can flash this model from the browser. SYNQ never does. */
  firmwareUpdateMethod: string | null;
  /** Gear Link UI bundle for this PID: https://gearlink.asus.com/view/<pid>/main-<version>-<id>.js */
  bundle: { version: string; id: string };
  flags: { hasPowerInfo?: boolean; supportsBooster?: boolean; hasOled?: boolean; hasHwCopilot?: boolean };
}

export const GEARLINK_SNAPSHOT = ${q(snapshot)};

export const GEARLINK_DEVICES: readonly GearLinkDevice[] = [
${lines.join("\n")}
];
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/lib/brands/asus/devices.generated.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`${rows.length} manifests -> ${target}`);
