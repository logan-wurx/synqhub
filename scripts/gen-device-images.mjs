// Writes src/lib/device-images.generated.ts from src/assets/devices/index.json (made by the photo pipeline) and
// checks every listed picture is on disk. The index maps a vid:pid or a model name to a picture; the pictures
// themselves are lazily imported (import.meta.glob), so one is only fetched when its device is shown.
//
//   node scripts/gen-device-images.mjs
//
// Nothing here talks to a device.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "assets", "devices");
const { models } = JSON.parse(readFileSync(join(dir, "index.json"), "utf8"));

/** Lower-case words joined by single spaces; the same form the resolver (src/lib/device-images.ts) compares in. */
const norm = (s) => s.toLowerCase().replace(/\+/g, " plus ").replace(/&/g, " and ").split(/[^a-z0-9]+/).filter(Boolean).join(" ");

const byId = new Map();
const dupes = new Set();
for (const m of models) {
  if (!existsSync(join(dir, m.vendor, `${m.key}.webp`))) throw new Error(`index lists ${m.vendor}/${m.key}.webp but the file is missing`);
  for (const id of m.ids) {
    if (byId.has(id) && byId.get(id) !== m.key) dupes.add(id);
    else byId.set(id, m.key);
  }
}
// An id two pictures claim says nothing about which one it is: drop it and let the name decide.
for (const id of dupes) byId.delete(id);
if (dupes.size) console.warn(`dropped ${dupes.size} ambiguous id(s): ${[...dupes].join(", ")}`);

const rows = models.map((m) => `  [${JSON.stringify(m.key)}, ${JSON.stringify(m.vendor)}, ${JSON.stringify(m.kind)}, ${JSON.stringify(m.name)}, ${JSON.stringify([...new Set([m.name, ...m.names].map(norm).filter(Boolean))])}],`).join("\n");
const ids = [...byId].sort((a, b) => (a[0] < b[0] ? -1 : 1)).map(([id, key]) => `  ${JSON.stringify(id)}: ${JSON.stringify(key)},`).join("\n");

writeFileSync(
  join(root, "src", "lib", "device-images.generated.ts"),
  `// GENERATED by scripts/gen-device-images.mjs from src/assets/devices/index.json. Do not edit.
//
// Product pictures from the makers' own sites, configurators and apps (see src/assets/devices/SOURCES.json).
// Product images are (c) their respective owners. Want one removed? Open an issue.
//
// ${models.length} pictures. DEVICE_IMAGE_MODELS lists them, DEVICE_IMAGE_BY_ID maps a vid:pid to one, and
// loadDeviceImage(key) imports the file only when it is asked for.

/** [key, vendor folder, kind, display name, normalised names a device may report] */
export type DeviceImageRow = readonly [string, string, "mouse" | "keyboard" | "gamepad" | "light" | "headset" | "monitor" | "webcam", string, readonly string[]];

export const DEVICE_IMAGE_MODELS: readonly DeviceImageRow[] = [
${rows}
];

/** "vid:pid" (lower-case hex, 4 digits each) -> model key. Ids that two pictures claim are left out. */
export const DEVICE_IMAGE_BY_ID: Readonly<Record<string, string>> = {
${ids}
};

// import.meta.glob is Vite's: the files become separate assets and only load on demand. Plain node (the test
// scripts) has no such function, so there the call throws and nothing loads.
const FILES: Record<string, () => Promise<string>> = (() => {
  try {
    return import.meta.glob<string>("../assets/devices/*/*.webp", { query: "?url", import: "default" });
  } catch {
    return {};
  }
})();

/** The URL of a picture, fetched on first use; null when there is no such picture. */
export async function loadDeviceImage(key: string): Promise<string | null> {
  const row = DEVICE_IMAGE_MODELS.find((m) => m[0] === key);
  const load = row && FILES[\`../assets/devices/\${row[1]}/\${key}.webp\`];
  return load ? load() : null;
}
`,
);
console.log(`device-images.generated.ts: ${models.length} pictures, ${byId.size} ids`);
