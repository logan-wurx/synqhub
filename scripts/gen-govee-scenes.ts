// Writes the Govee tables for the app and the bridge from scripts/lighting/govee/models.json (which models, how they
// take colour) and catalogue.json (each model's scenes; Beshelmek/govee_ble_lights, MIT, see SOURCE):
//
//   src/lib/lighting/govee/models.generated.ts   the models (small: the Devices home reads it)
//   src/lib/lighting/govee/scenes.generated.ts   every model's scenes, their data and preview colours (the lamp page)
//   src-tauri/src/lighting/govee/catalogue.rs    the models, the scene codes and the data the guard compares
//   src-tauri/src/lighting/govee/scenes.bin      the scene data itself (deduplicated; included by catalogue.rs)
//
// Run after either JSON changes:  node scripts/gen-govee-scenes.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { KELVIN_STEP, kelvinRgb } from "../src/lib/lighting/govee/kelvin.ts";
import type { Catalogue } from "./lighting/govee/extract-catalogue.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const MODELS = join(root, "scripts/lighting/govee/models.json");
const CATALOGUE = join(root, "scripts/lighting/govee/catalogue.json");
export const MODELS_OUT = join(root, "src/lib/lighting/govee/models.generated.ts");
export const TS_OUT = join(root, "src/lib/lighting/govee/scenes.generated.ts");
export const RS_OUT = join(root, "src-tauri/src/lighting/govee/catalogue.rs");
export const BIN_OUT = join(root, "src-tauri/src/lighting/govee/scenes.bin");

interface ModelIn {
  name?: string;
  kind?: string;
  dialect?: string;
  dialects?: string[];
  segments?: number;
  kelvin?: [number, number] | null;
  brightnessMax?: number;
  music?: [string, string][];
  diy?: boolean;
  proven?: string[];
}

/** Preview colours of scenes that carry no data to read them from (for the swatch only). */
const BUILT_IN_SWATCH: Record<string, string[]> = {
  Leisure: ["ffb347", "ff7f50", "ffd27f"],
  "Night Light": ["ff9a3c", "ff7a1a"],
  Fireworks: ["ff2d55", "ffd60a", "0a84ff", "30d158"],
  Stacking: ["ff375f", "ff9f0a", "64d2ff"],
  "Bouncing Ball": ["30d158", "0a84ff", "ffd60a"],
  Bubble: ["64d2ff", "bf5af2", "5e5ce6"],
  Rainbow: ["ff0000", "ff7f00", "ffff00", "00ff00", "0000ff", "8b00ff"],
  Meteor: ["ffffff", "64d2ff", "0a84ff"],
  Ripple: ["00c7be", "0a84ff", "5e5ce6"],
};

/** The colour lists of a V1 scene blob: [count] ([len][body])…, body = 6 bytes, N x 6, colorIc, 2 bytes, M, M x RGB, 7 bytes. */
export function blobColours(blob: Uint8Array): string[] {
  const out: string[] = [];
  let p = 1;
  for (let e = 0; e < blob[0]; e++) {
    const len = blob[p];
    const body = blob.subarray(p + 1, p + 1 + len);
    p += 1 + len;
    const n = body[5];
    const at = 6 + 6 * n;
    const m = body[at + 3];
    if (len !== 17 + 6 * n + 3 * m) throw new Error("scene blob doesn't parse");
    for (let i = 0; i < m; i++) out.push(Array.from(body.subarray(at + 4 + 3 * i, at + 7 + 3 * i), (b) => b.toString(16).padStart(2, "0")).join(""));
  }
  if (!blob.subarray(p).every((b) => b === 0)) throw new Error("scene blob has data after its effects");
  return out;
}

const bytes = (h: string) => Uint8Array.from(h.match(/../g) ?? [], (x) => parseInt(x, 16));

export function generated(): { models: string; ts: string; rs: string; bin: Uint8Array } {
  const spec = JSON.parse(readFileSync(MODELS, "utf8")) as { defaults: Required<Omit<ModelIn, "name">>; models: Record<string, ModelIn> };
  const cat = JSON.parse(readFileSync(CATALOGUE, "utf8")) as Catalogue;
  const skus = [...new Set([...Object.keys(cat.skus), ...Object.keys(spec.models)])].sort();
  const models = skus.map((sku) => {
    const m = { ...spec.defaults, ...spec.models[sku] };
    return { sku, name: spec.models[sku]?.name ?? sku, kind: m.kind, dialect: parseInt(m.dialect, 16), dialects: m.dialects.map((d) => parseInt(d, 16)), segments: m.segments, kelvin: m.kelvin, brightnessMax: m.brightnessMax, music: m.music.map(([id, name]) => ({ id: parseInt(id, 16), name })), diy: m.diy, proven: m.proven, scenes: cat.skus[sku]?.length ?? 0 };
  });

  // Preview colours per blob (unique), then per scene.
  const blobCols = cat.blobs.map((h) => {
    try {
      const cs = [...new Set(blobColours(bytes(h)).filter((x) => x !== "000000"))].slice(0, 6);
      return cs.length ? cs : null;
    } catch {
      return null;
    }
  });

  const modelsTs = `// GENERATED by scripts/gen-govee-scenes.ts from scripts/lighting/govee/models.json and catalogue.json. Do not edit.
//
// The Govee models SYNQ drives (${models.length}): how each takes colour (the dialect it starts with and the ones the guard
// lets through), its segments, white range, brightness scale, music modes and DIY, what the developer has proven on it, and
// how many scenes its catalogue has. docs/devices/LIGHTING.md says what is still UNVERIFIED.

export interface GoveeModel {
  sku: string;
  name: string;
  kind: string;
  dialect: number;
  dialects: readonly number[];
  segments: number;
  kelvin: readonly [number, number] | null;
  brightnessMax: number;
  music: readonly { id: number; name: string }[];
  diy: boolean;
  proven: readonly string[];
  scenes: number;
}

export const GOVEE_MODELS: Readonly<Record<string, GoveeModel>> = {
${models.map((m) => `  ${m.sku}: ${JSON.stringify(m)},`).join("\n")}
};
`;

  const ts = `// GENERATED by scripts/gen-govee-scenes.ts from scripts/lighting/govee/catalogue.json (${cat.source}). Do not edit.
//
// Every Govee model's scenes: ${Object.values(cat.skus).reduce((n, r) => n + r.length, 0)} across ${Object.keys(cat.skus).length} models, ${cat.blobs.length} parameter blobs (shared between models).
// A scene with data is uploaded before it is switched on; the rest are built into the lamp. Preview colours come from
// a scene's own data where it uses the V1 layout, else a stable guess from its name.

export interface LightScene {
  code: number;
  name: string;
  category: string;
  /** The parameter data, sent as an A3 upload before the scene frame (null: built into the lamp). */
  blob: string | null;
  colours: readonly string[];
}

const BLOBS: readonly string[] = ${JSON.stringify(cat.blobs)};
const BLOB_COLOURS: readonly (readonly string[] | null)[] = ${JSON.stringify(blobCols)};
const SWATCH: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(BUILT_IN_SWATCH)};
const ROWS: Readonly<Record<string, readonly (readonly [number, string, string, number])[]>> = ${JSON.stringify(cat.skus)};

/** Three colours from a name, for a scene whose data isn't the V1 layout (a stable guess, for the swatch only). */
function nameColours(name: string): string[] {
  let h = 0;
  for (const c of name) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return [0, 1, 2].map((i) => {
    const hue = (h % 360) + i * 47;
    const f = (n: number) => {
      const k = (n + hue / 60) % 6;
      return Math.round(255 * (1 - 0.75 * Math.max(0, Math.min(k, 4 - k, 1))));
    };
    return [f(5), f(3), f(1)].map((v) => v.toString(16).padStart(2, "0")).join("");
  });
}

const built = new Map<string, readonly LightScene[]>();
/** A model's scenes, in the catalogue's order (empty for a model without a catalogue). */
export function scenesFor(sku: string): readonly LightScene[] {
  let s = built.get(sku);
  if (!s) {
    s = (ROWS[sku] ?? []).map(([code, name, category, at]) => ({ code, name, category, blob: at >= 0 ? BLOBS[at] : null, colours: (at >= 0 ? BLOB_COLOURS[at] : SWATCH[name]) ?? nameColours(name) }));
    built.set(sku, s);
  }
  return s;
}

const bytes = (h: string) => Uint8Array.from(h.match(/../g) ?? [], (x) => parseInt(x, 16));
export const sceneBlob = (s: LightScene): Uint8Array | null => (s.blob ? bytes(s.blob) : null);
/** The parameter data of a model's scene, by code (undefined: not in its catalogue; null: built in). */
export function sceneData(sku: string, code: number): Uint8Array | null | undefined {
  const row = ROWS[sku]?.find((r) => r[0] === code);
  return row ? (row[3] >= 0 ? bytes(BLOBS[row[3]]) : null) : undefined;
}
`;

  // The bridge: one binary file of all blobs, and offsets into it.
  const offsets: [number, number][] = [];
  let total = 0;
  for (const h of cat.blobs) {
    offsets.push([total, h.length / 2]);
    total += h.length / 2;
  }
  const bin = new Uint8Array(total);
  cat.blobs.forEach((h, i) => bin.set(bytes(h), offsets[i][0]));
  const rows = Object.entries(cat.skus).flatMap(([sku, rs]) => rs.map(([code, , , at]) => [sku, code, at] as const)).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[1] - b[1]));
  const kelvinRange = models.flatMap((m) => (m.kelvin ? [m.kelvin[0], m.kelvin[1]] : []));
  const kelvins: number[] = [];
  for (let k = Math.min(...kelvinRange); k <= Math.max(...kelvinRange); k += KELVIN_STEP) kelvins.push(k);
  const rs = `//! GENERATED by scripts/gen-govee-scenes.ts from scripts/lighting/govee/models.json and catalogue.json
//! (${cat.source}). Do not edit. The models the guard knows, each model's scene codes and the data an upload must equal.

/// How one model takes colour and what else it has (src/lib/lighting/govee/models.generated.ts).
pub struct Model {
    pub sku: &'static str,
    /// The colour sub-modes the guard lets through (0x02, 0x0b, 0x0d, 0x15).
    pub dialects: &'static [u8],
    /// Segments (0: one colour for the whole light; then the guard allows the dialect's full mask).
    pub segments: u8,
    pub kelvin: Option<(u16, u16)>,
    pub brightness_max: u8,
    pub music: &'static [u8],
    pub diy: bool,
}

pub const MODELS: [Model; ${models.length}] = [
${models.map((m) => `    Model { sku: "${m.sku}", dialects: &[${m.dialects.map((d) => `0x${d.toString(16).padStart(2, "0")}`).join(", ")}], segments: ${m.segments}, kelvin: ${m.kelvin ? `Some((${m.kelvin[0]}, ${m.kelvin[1]}))` : "None"}, brightness_max: ${m.brightnessMax}, music: &[${m.music.map((x) => `0x${x.id.toString(16).padStart(2, "0")}`).join(", ")}], diy: ${m.diy} },`).join("\n")}
];

/// Every scene: (model, code, index of its data in \`BLOB_AT\` or NONE when built in), sorted by model then code.
pub const SCENES: [(&str, u16, u16); ${rows.length}] = [
${rows.map(([sku, code, at]) => `    ("${sku}", ${code}, ${at >= 0 ? at : "NONE"}),`).join("\n")}
];
pub const NONE: u16 = u16::MAX;

/// The scene data, deduplicated: (offset, length) in \`SCENE_DATA\`.
pub const BLOB_AT: [(u32, u16); ${offsets.length}] = [${offsets.map(([o, n]) => `(${o}, ${n})`).join(", ")}];
pub static SCENE_DATA: &[u8] = include_bytes!("scenes.bin");

/// White: each colour temperature SYNQ sends (${kelvins[0]}-${kelvins[kelvins.length - 1]} K in steps of ${KELVIN_STEP}) and the RGB rendering that goes with it.
pub const KELVIN_RGB: [(u16, [u8; 3]); ${kelvins.length}] = [${kelvins.map((k) => `(${k}, [${kelvinRgb(k).join(", ")}])`).join(", ")}];
`;
  return { models: modelsTs, ts, rs, bin };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const g = generated();
  writeFileSync(MODELS_OUT, g.models);
  writeFileSync(TS_OUT, g.ts);
  writeFileSync(RS_OUT, g.rs);
  writeFileSync(BIN_OUT, g.bin);
  console.log(`wrote ${MODELS_OUT}, ${TS_OUT}, ${RS_OUT} and ${BIN_OUT} (${g.bin.length} bytes of scene data)`);
}
