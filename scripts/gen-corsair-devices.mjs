// Writes src/lib/brands/corsair/devices.generated.ts from the CORSAIR Web Hub device table.
//
// Source: https://www.corsair.com/web-hub/ loads ./assets/<hash>.js (BDiHBs-c.js on 2026-10-13). That
// bundle holds the device table as a string literal: `l2e=JSON.parse('[...]'),bn={devices:l2e}`.
// Download the bundle with curl (data only; it is never executed), then:
//   node scripts/gen-corsair-devices.mjs <path to the Web Hub main bundle> [snapshot date]
// The script finds the literal as text, un-escapes it and JSON.parses it. Only the fields below are kept.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const file = process.argv[2];
const snapshot = process.argv[3] ?? new Date().toISOString().slice(0, 10);
if (!file) {
  console.error("usage: node scripts/gen-corsair-devices.mjs <Web Hub main bundle .js> [snapshot date]");
  process.exit(1);
}
const text = fs.readFileSync(file, "utf8");
const start = text.indexOf("JSON.parse('[{\"type\":");
if (start < 0) throw new Error("device table literal not found");
const from = start + "JSON.parse('".length;
const end = text.indexOf("')", from);
const literal = text.slice(from, end).replace(/\\'/g, "'").replace(/\\\\/g, "\\");
const devices = JSON.parse(literal);
if (!Array.isArray(devices) || devices.length < 10) throw new Error("unexpected table shape");

const POLL = [125, 250, 500, 1000, 2000, 4000, 8000];
const hz = (arr) => (Array.isArray(arr) ? arr.map((i) => POLL[i]).filter(Boolean) : []);
const q = (s) => JSON.stringify(s);
const num = (v) => (typeof v === "number" ? v : "null");

const rows = devices
  .map((d) => {
    const pid = parseInt(d.pid, 16);
    const kind = d.type === "dongle" ? "receiver" : d.type;
    const act = d.actuationDistanceRange?.supported;
    const dpi = d.dpiConfig;
    return {
      pid,
      text: `  { pid: 0x${d.pid.toLowerCase()}, kind: ${q(kind)}, name: ${q(d.retailShortName)}, description: ${q(d.description ?? "")}, bragiVersion: ${num(d.bragiProtocolVersion)}, multiSession: ${!!d.supportMultiSessionControl}, listedInPicker: ${d.allowAuthentication !== false}, configInHostControl: ${!!d.configInHostControl}, supportsProfile: ${d.supportsProfile !== false}, profileMax: ${num(d.profileMax)}, keyAssignmentVersion: ${num(d.keyAssignmentVersion)}, redirect: ${q(d.redirectUrl ?? null)}, actuationMm: ${act ? `[${act.min}, ${act.max}]` : "null"}, pollingWiredHz: ${q(hz(d.pollingRate?.wiredPollingRate))}, pollingWirelessHz: ${q(hz(d.pollingRate?.wirelessPollingRate))}, dpi: ${dpi ? `{ min: ${dpi.minDpiValue}, max: ${dpi.maxDpiValue}, step: ${dpi.stepValue} }` : "null"}, liftHeights: ${q(d.liftHeights ?? [])}, keysNotAllowForActuation: ${q(d.keysNotAllowForActuation ?? [])}, keysNotAllowForFlashTap: ${q(d.keysNotAllowForFlashTap ?? [])}, resetDebugMode: ${!!d.resetDebugMode}, gameModeRtOverride: ${!!d.useGameModeRapidTriggerOverrideEnabled}, services: ${q(d.services ?? [])} },`,
    };
  })
  .sort((a, b) => a.pid - b.pid);

const out = `// GENERATED by scripts/gen-corsair-devices.mjs from the CORSAIR Web Hub device table. Do not edit by hand.
// Source (public, read as text): https://www.corsair.com/web-hub/assets/BDiHBs-c.js, literal
// \`l2e=JSON.parse('[...]')\` exported as \`bn.devices\`; snapshot ${snapshot}, ${rows.length} devices.
// Polling arrays are converted from Web Hub's indices (0..6 = 125..8000 Hz) to Hz.

export interface WebHubDevice {
  pid: number;
  kind: "keyboard" | "mouse" | "receiver";
  name: string;
  description: string;
  /** Table's bragiProtocolVersion (1, 1.5, 2) or null when absent. */
  bragiVersion: number | null;
  /** supportMultiSessionControl: the device takes Bragi 1.5 session framing. */
  multiSession: boolean;
  /** allowAuthentication: offered in Web Hub's device picker. */
  listedInPicker: boolean;
  /** configInHostControl: Web Hub wraps file reads/writes in operating mode 2 (host controlled). */
  configInHostControl: boolean;
  supportsProfile: boolean;
  profileMax: number | null;
  keyAssignmentVersion: number | null;
  /** "SABRE": handed to the separate Sabre Web Hub (not Bragi). */
  redirect: string | null;
  /** actuationDistanceRange.supported, mm. */
  actuationMm: readonly [number, number] | null;
  pollingWiredHz: readonly number[];
  pollingWirelessHz: readonly number[];
  dpi: { min: number; max: number; step: number } | null;
  liftHeights: readonly number[];
  keysNotAllowForActuation: readonly number[];
  keysNotAllowForFlashTap: readonly number[];
  resetDebugMode: boolean;
  gameModeRtOverride: boolean;
  services: readonly string[];
}

export const WEBHUB_SNAPSHOT = ${q(snapshot)};

export const WEBHUB_DEVICES: readonly WebHubDevice[] = [
${rows.map((r) => r.text).join("\n")}
];
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/lib/brands/corsair/devices.generated.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`${rows.length} devices -> ${target}`);
