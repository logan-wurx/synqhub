// Writes src/lib/kb/via/keychron/catalog.generated.ts from a tree of Keychron's published QMK firmware
// (https://github.com/Keychron/qmk_firmware, branch 2025q3, GPL-2.0-or-later). Only the data files of the Hall-effect
// keyboards are read (keyboards/<keychron|lemokey>/<board>_he/info.json and <variant>/keyboard.json); no firmware
// code is imported or run, and only facts are kept: USB ids, matrix size and where each key sits.
//
// Run: node scripts/gen-keychron-he-catalog.mjs <directory holding keyboards/> [commit id]
//
// The directory needs just those JSON files (fetched read-only from raw.githubusercontent.com); a full checkout
// works too. Every board with an `_he` folder is listed: K2/K4/K6/K8/K10 HE, Q0/Q1/Q2/Q3/Q4/Q5/Q6/Q12 HE and Lemokey
// L1/P1/P2/P3 HE, in the variants (ANSI / ISO / JIS) the firmware names. Wired USB ids only: a wireless dongle has its own.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [dir, commit = "unknown"] = process.argv.slice(2);
if (!dir) throw new Error("usage: node scripts/gen-keychron-he-catalog.mjs <directory holding keyboards/> [commit id]");

const parse = (t) => {
  try {
    return JSON.parse(t);
  } catch {
    return JSON.parse(t.replace(/^\s*\/\/.*$/gm, ""));
  }
};
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const num = (s) => parseInt(String(s), 16);

const files = walk(path.join(dir, "keyboards")).map((f) => f.split(path.sep).join("/"));
const infos = files.filter((f) => /keyboards\/(keychron|lemokey)\/[^/]+_he\/info\.json$/.test(f)).sort();
const models = [];
const layouts = [];
const layoutIds = new Map();
const layoutOf = (keys) => {
  const rows = keys.map((k) => [k.matrix[0], k.matrix[1], Math.round((k.x ?? 0) * 1000) / 1000, Math.round((k.y ?? 0) * 1000) / 1000, k.w ?? 1, k.h ?? 1]);
  const id = JSON.stringify(rows);
  if (!layoutIds.has(id)) {
    layoutIds.set(id, layouts.length);
    layouts.push(rows);
  }
  return layoutIds.get(id);
};

const variantName = (v) => (/ansi/.test(v) ? "ANSI" : /iso/.test(v) ? "ISO" : /jis/.test(v) ? "JIS" : "");

for (const f of infos) {
  const info = parse(fs.readFileSync(f, "utf8"));
  const base = f.replace(/\/info\.json$/, "");
  const rows = info.matrix_pins?.rows?.length;
  const cols = info.matrix_pins?.cols?.length;
  if (!rows || !cols) throw new Error(`${f}: no matrix size`);
  const brand = info.manufacturer;
  const family = base.split("/").pop();
  for (const g of files.filter((x) => x.startsWith(base + "/") && x.endsWith("/keyboard.json")).sort()) {
    const kb = parse(fs.readFileSync(g, "utf8"));
    const variant = path.posix.relative(base, path.posix.dirname(g));
    const layoutKey = Object.keys(kb.layouts)[0];
    const keys = kb.layouts[layoutKey].layout;
    if (keys.some((k) => k.matrix[0] >= rows || k.matrix[1] >= cols)) throw new Error(`${g}: a key outside the ${rows}x${cols} matrix`);
    models.push({
      vid: num(info.usb.vid),
      pid: num(kb.usb.pid),
      brand,
      name: info.keyboard_name.replace(/^(Keychron|Lemokey)\s+/, ""),
      variant: variantName(variant),
      family,
      rows,
      cols,
      layout: layoutOf(keys),
    });
  }
}
models.sort((a, b) => a.vid - b.vid || a.pid - b.pid);
const seen = new Set();
for (const m of models) {
  const k = `${m.vid}:${m.pid}`;
  if (seen.has(k)) throw new Error(`duplicate ${k}`);
  seen.add(k);
}

const hex = (n) => `0x${n.toString(16).padStart(4, "0")}`;
const body = `// GENERATED by scripts/gen-keychron-he-catalog.mjs from Keychron's QMK firmware (github.com/Keychron/qmk_firmware,
// branch 2025q3, commit ${commit}), GPL-2.0-or-later. Do not edit.
//
// The ${models.length} wired Hall-effect keyboards that firmware builds: Keychron K2 / K4 / K6 / K8 / K10 HE, Q0 / Q1 / Q2 / Q3 /
// Q4 / Q5 / Q6 / Q12 HE and Lemokey L1 / P1 / P2 / P3 HE. Facts only (USB ids, matrix size, key positions in key units from
// each variant's keyboard.json); SYNQ is AGPL-3.0, which GPL-2.0-or-later code may be combined with.

export interface KcModel {
  vendorId: number;
  productId: number;
  brand: "Keychron" | "Lemokey";
  /** "Q1 HE" */
  name: string;
  /** "ANSI", "ISO", "JIS" or "". */
  variant: string;
  /** Firmware folder: "q1_he". */
  family: string;
  /** The matrix the firmware scans (rows x columns); key index = row * cols + col. */
  rows: number;
  cols: number;
  /** Index into KC_LAYOUTS. */
  layout: number;
}

/** [row, col, x, y, w, h] per key, in key units. */
export type KcLayoutRow = readonly [number, number, number, number, number, number];

export const KC_MODELS: readonly KcModel[] = [
${models.map((m) => `  { vendorId: ${hex(m.vid)}, productId: ${hex(m.pid)}, brand: ${JSON.stringify(m.brand)}, name: ${JSON.stringify(m.name)}, variant: ${JSON.stringify(m.variant)}, family: ${JSON.stringify(m.family)}, rows: ${m.rows}, cols: ${m.cols}, layout: ${m.layout} },`).join("\n")}
];

export const KC_LAYOUTS: readonly (readonly KcLayoutRow[])[] = [
${layouts.map((l) => `  [${l.map((r) => `[${r.join(",")}]`).join(",")}],`).join("\n")}
];
`;
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/lib/kb/via/keychron/catalog.generated.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`${models.length} boards, ${layouts.length} layouts -> ${out}`);
