// Writes src/lib/web/ids.generated.ts: the USB-id tables the website's device policy needs
// (src/lib/web/policy.ts), read from the very Rust tables the desktop bridge uses so the two can't
// drift. It parses brand_ids.rs (made by gen-brand-bridge.ts from the drivers' device tables) and
// openmouse_ids.rs (made by gen-openmouse-index.mjs from OpenMouse's filters), and takes the ASUS
// family map from asus-rules.json. scripts/web-guard.test.ts regenerates the text and compares.
//
//   node scripts/gen-web-ids.ts
//
// Nothing here talks to a device.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { brandIdsText } from "./gen-brand-bridge.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const num = (s: string) => parseInt(s, 16);
const hex = (n: number) => `0x${n.toString(16).padStart(4, "0")}`;

/** Every `pub const NAME: [...] = [ ... ];` of a Rust table file, as its list of number groups. */
function consts(text: string): Map<string, number[][]> {
  const out = new Map<string, number[][]>();
  for (const m of text.matchAll(/pub const (\w+): \[[^;]+; \d+\] = \[([\s\S]*?)\];/g)) {
    const body = m[2].replace(/Some\((0x[0-9a-f]+)\)/g, "$1");
    if (body.includes("(")) {
      const rows = [...body.matchAll(/\(([^)]*)\)/g)].map((r) => [...r[1].matchAll(/None|0x[0-9a-f]+/g)].map((x) => (x[0] === "None" ? -1 : num(x[0]))));
      out.set(m[1], rows);
    } else out.set(m[1], [[...body.matchAll(/0x[0-9a-f]+|\b\d+\b/g)].map((x) => (x[0].startsWith("0x") ? num(x[0]) : Number(x[0])))]);
  }
  return out;
}

const list = (name: string, doc: string, values: number[]) => `/** ${doc} */\nexport const ${name}: readonly number[] = [${values.map(hex).join(", ")}];\n`;
const pairs = (name: string, doc: string, rows: number[][]) =>
  `/** ${doc} */\nexport const ${name}: readonly (readonly [number, number])[] = [${rows.map(([v, p]) => `[${hex(v)}, ${hex(p)}]`).join(", ")}];\n`;
const quads = (name: string, doc: string, rows: number[][], optional: boolean) =>
  `/** ${doc} */\nexport const ${name}: readonly (readonly [number, ${optional ? "number | null" : "number"}, number | null, number | null])[] = [${rows
    .map((r) => `[${r.map((x) => (x < 0 ? "null" : hex(x))).join(", ")}]`)
    .join(", ")}];\n`;

export function webIdsText(): string {
  const brand = consts(brandIdsText());
  const om = consts(readFileSync(join(root, "src-tauri/src/openmouse_ids.rs"), "utf8"));
  const asus = JSON.parse(readFileSync(join(root, "src/lib/brands/asus/asus-rules.json"), "utf8")) as { familyByPid: Record<string, string> };
  const b = (n: string) => {
    const v = brand.get(n);
    if (!v) throw new Error(`brand_ids.rs has no ${n}`);
    return v;
  };
  const flat = (n: string) => b(n)[0];
  const o = (n: string) => {
    const v = om.get(n);
    if (!v) throw new Error(`openmouse_ids.rs has no ${n}`);
    return v;
  };
  const family = Object.entries(asus.familyByPid).map(([pid, f]) => [num(pid), f] as const).sort((x, y) => x[0] - y[0]);
  return `// GENERATED by scripts/gen-web-ids.ts from src-tauri/src/brand_ids.rs, openmouse_ids.rs and asus-rules.json. Do not edit.
//
// The USB-id tables behind the website's device policy (src/lib/web/policy.ts). They are the same
// tables the desktop bridge compiles in, so the chooser filters, the device list and the guarded proxy
// agree with the Rust bridge on which devices and collections SYNQ may touch.

${pairs("SONIX", "Sonix HE boards (FCC protocol).", b("SONIX"))}${pairs("MONSGEEK", "MonsGeek / Akko.", b("MONSGEEK"))}${pairs("DRUNKDEER", "DrunkDeer on its own vendor id.", b("DRUNKDEER"))}${pairs("DRUNKDEER_X60", "DrunkDeer X60 on a borrowed vendor id (the product string must also say so).", b("DRUNKDEER_X60"))}${pairs("FW19F5_MCHOSE", "MCHOSE first-generation keyboards (0x19F5 firmware family).", b("FW19F5_MCHOSE"))}${pairs("FW19F5_DRUNKDEER", "DrunkDeer gen-2 boards on 0x19F5.", b("FW19F5_DRUNKDEER"))}${pairs("FW19F5_NUPHY", "NuPhy V3 / HE boards (read-only).", b("FW19F5_NUPHY"))}${pairs("FW19F5_RK_GCOME", "Royal Kludge Gcome boards (read-only).", b("FW19F5_RK_GCOME"))}${pairs("RK_BEIYING", "Royal Kludge BeiYing boards (System Control, feature reports, write-only).", b("RK_BEIYING"))}${pairs("SPARKLINK", "SparkLink keyboards (Royal Kludge C / M75 HE, AULA HE, Kochi) on 0xFFA0:0x0001.", b("SPARKLINK"))}${pairs("KEYCHRON_HE", "Keychron / Lemokey Hall-effect keyboards: VIA's raw-HID channel plus Keychron's analog commands.", b("KEYCHRON_HE"))}${list("RAZER_KEYBOARDS", "Razer analog keyboards (vendor 0x1532).", flat("RAZER_KEYBOARDS"))}${list("RAZER_BRAND_MICE", "Razer mice the brand driver knows.", flat("RAZER_BRAND_MICE"))}${pairs("BYTECH", "Bytech-based boards read with one fixed request (report 9).", b("BYTECH"))}${list("ASUS_BOOTLOADER", "ASUS Gear Link bootloader PIDs.", flat("ASUS_BOOTLOADER"))}${list("CORSAIR_BRAGI_KEYBOARDS", "Corsair Bragi keyboards and receivers.", flat("CORSAIR_BRAGI_KEYBOARDS"))}${list("CORSAIR_BRAGI_MICE", "Corsair Bragi mice.", flat("CORSAIR_BRAGI_MICE"))}${list("CORSAIR_SABRE", "Corsair Sabre v2 mice.", flat("CORSAIR_SABRE"))}${list("CORSAIR_BRAGI_V1", "Corsair ids on Bragi 1.0 framing.", flat("CORSAIR_BRAGI_V1"))}${list("ICUE_KEYBOARDS", "Corsair iCUE keyboards.", flat("ICUE_KEYBOARDS"))}${list("ICUE_MICE", "Corsair iCUE mice.", flat("ICUE_MICE"))}${list("LOGITECH_KEYBOARDS", "Logitech G keyboards over HID++ 2.0.", flat("LOGITECH_KEYBOARDS"))}${list("STEELSERIES", "SteelSeries Apex keyboards SYNQ drives.", flat("STEELSERIES"))}${list("STEELSERIES_BOOTLOADER", "SteelSeries bootloader PIDs.", flat("STEELSERIES_BOOTLOADER"))}${list("SS_LEGACY", "SteelSeries family legacy.", flat("SS_LEGACY"))}${list("SS_SINGLE", "SteelSeries family single.", flat("SS_SINGLE"))}${list("SS_RX", "SteelSeries family wireless-rx.", flat("SS_RX"))}${list("SS_USB", "SteelSeries family wireless-usb.", flat("SS_USB"))}${pairs("LISTED_KEYBOARDS", "Wave 3a / 4 keyboards a registered driver claims: the only ones shown in the device list.", b("LISTED_KEYBOARDS"))}
/** ASUS Gear Link: product id -> command family (asus-rules.json familyByPid). */
export const ASUS_FAMILY: Readonly<Record<number, string>> = {${family.map(([p, f]) => `${hex(p)}: ${JSON.stringify(f)}`).join(", ")}};

${quads("OPENMOUSE_FILTERS", "OpenMouse's SUPPORTED_HID_FILTERS: [vendor id, product id, usage page, usage], null = any.", o("FILTERS"), true)}
${list("LOGITECH_MOUSE_PIDS", "Logitech ids that are always a mouse.", o("LOGITECH_MOUSE_PIDS")[0])}${list("RAZER_FEATURE_ONLY_PIDS", "Razer ids whose OpenMouse driver talks to the mouse or consumer collection by feature reports only.", o("RAZER_FEATURE_ONLY_PIDS")[0])}${quads("KEYBOARD_FILTERS", "Configuration collections of the keyboards @openmouse/keyboard-protocol drives: [vendor id, product id, usage page, usage].", o("KEYBOARD_FILTERS"), false)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(root, "src/lib/web/ids.generated.ts");
  writeFileSync(out, webIdsText());
  console.log(`wrote ${out}`);
}
