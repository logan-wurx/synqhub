// Writes src/lib/brands/fw19f5/mchose-catalog.generated.ts from a checkout of Fighting Control Center (FCC,
// https://github.com/shybruh/FightingControlCenter-FCC, GPL-3.0-or-later). Only FCC's JSON data is read
// (app/src/devices/mc-catalog.json); no FCC code is imported or run.
//
// Run: node scripts/gen-fw19f5-catalog.mjs <path to the FCC checkout>
//
// mc-catalog.json is "www.mchose.com.cn (MCHOSE web driver)", built 2026-10-10: the 28 first-generation
// ("glw" firmware) MCHOSE magnetic keyboards, with their USB ids, travel step, key slots and layouts.
// Boards that share a layout (the Ace 60 / 60 Pro / 60X, ...) point at one layout row set.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const fcc = process.argv[2];
if (!fcc) throw new Error("usage: node scripts/gen-fw19f5-catalog.mjs <FCC checkout>");
const catalog = JSON.parse(fs.readFileSync(path.join(fcc, "app/src/devices/mc-catalog.json"), "utf8"));

function commitOf(dir) {
  try {
    const head = fs.readFileSync(path.join(dir, ".git/HEAD"), "utf8").trim();
    if (!head.startsWith("ref: ")) return head;
    const ref = head.slice(5);
    const loose = path.join(dir, ".git", ref);
    if (fs.existsSync(loose)) return fs.readFileSync(loose, "utf8").trim();
    const packed = fs.readFileSync(path.join(dir, ".git/packed-refs"), "utf8");
    return packed.split("\n").find((l) => l.endsWith(" " + ref))?.split(" ")[0] ?? "unknown";
  } catch {
    return "unknown";
  }
}

/** "电竞版" / "超竞版" edition names, in English (as FCC's registry does). */
const cleanName = (n) => n.replace("(电竞版)", " (Esports)").replace("(超竞版)", " (Ultra)").replace(/\s+/g, " ").trim();
const round = (v) => Math.round(Number(v) * 1000) / 1000;

// One layout per distinct key list. Rows: [slot, HID usage (0 = Fn), x, y, w, h].
const layoutIds = new Map();
const layouts = [];
const layoutOf = (d) => {
  const rows = d.keys.map(([slot, hid, x, y, w, h]) => [slot, hid, round(x), round(y), round(w), round(h || 1)]);
  const sig = JSON.stringify(rows);
  if (!layoutIds.has(sig)) {
    layoutIds.set(sig, `l${layouts.length}`);
    layouts.push({ id: `l${layouts.length}`, from: d.id, rows });
  }
  return layoutIds.get(sig);
};

const boards = catalog.devices.map((d) => ({
  id: d.id,
  name: cleanName(d.name),
  ids: d.identities,
  type: d.type,
  step: d.step,
  minTravel: d.minTravel,
  precision: d.precision,
  maxTravel: d.maxTravel,
  maxKeyCount: d.maxKeyCount,
  wireless: d.wireless,
  effects: d.effects,
  layout: layoutOf(d),
}));

const hex4 = (n) => "0x" + n.toString(16).padStart(4, "0");
const commit = commitOf(fcc);
const out = [
  "// GENERATED by scripts/gen-fw19f5-catalog.mjs. Do not edit by hand.",
  "//",
  "// Data from Fighting Control Center (FCC), https://github.com/shybruh/FightingControlCenter-FCC,",
  `// commit ${commit}, file app/src/devices/mc-catalog.json (docs/PROTOCOL-MC.md describes the protocol).`,
  "// FCC is licensed under the GNU GPL v3.0 or later; this derived table is distributed under the same",
  "// terms as part of SYNQ (AGPL-3.0, which is GPL-3-compatible). FCC built its catalog from the official",
  `// MCHOSE web driver ("${catalog.source}", built ${catalog.builtAt}).`,
  "//",
  "// The first-generation MCHOSE magnetic keyboards (\"glw\" firmware). Travel: `step` raw units per mm,",
  "// `precision` the smallest rapid-trigger step in mm, `maxTravel` in mm. Layout rows are",
  "// [key slot, HID usage (0 = Fn / none), x, y, w, h] in key units; the slot addresses the key map and the",
  "// key-trigger table (8 bytes per key).",
  "",
  "export interface McBoard {",
  "  /** FCC's model id. */",
  "  id: string;",
  "  name: string;",
  "  /** Every USB identity the official driver lists for it: [vendor id, product id]. */",
  "  ids: readonly (readonly [number, number])[];",
  "  /** MCHOSE's firmware type number (FCC `type`). */",
  "  type: number;",
  "  /** Raw actuation units per mm. */",
  "  step: number;",
  "  minTravel: number;",
  "  /** The smallest rapid-trigger step, in mm. */",
  "  precision: number;",
  "  maxTravel: number;",
  "  maxKeyCount: number;",
  "  /** The lighting effects the official driver offers for it, in its order (empty: none listed). */",
  "  effects: readonly number[];",
  "  /** Key into MC_LAYOUTS. */",
  "  layout: string;",
  "}",
  "",
  "/** [key slot, HID usage, x, y, w, h] per key. */",
  "export type McLayoutKey = readonly [number, number, number, number, number, number];",
  "",
  `export const MC_CATALOG_SOURCE = { repo: "https://github.com/shybruh/FightingControlCenter-FCC", commit: "${commit}", extracted: ${JSON.stringify(`${catalog.source}, built ${catalog.builtAt}`)} } as const;`,
  "",
  "export const MC_BOARDS: readonly McBoard[] = [",
  ...boards.map(
    (b) =>
      `  { id: ${JSON.stringify(b.id)}, name: ${JSON.stringify(b.name)}, ids: [${b.ids.map(([v, p]) => `[${hex4(v)}, ${hex4(p)}]`).join(", ")}], type: ${b.type}, step: ${b.step}, minTravel: ${b.minTravel}, precision: ${b.precision}, maxTravel: ${b.maxTravel}, maxKeyCount: ${b.maxKeyCount}, effects: [${b.effects.join(",")}], layout: ${JSON.stringify(b.layout)} },`,
  ),
  "];",
  "",
  "export const MC_LAYOUTS: Readonly<Record<string, readonly McLayoutKey[]>> = {",
  ...layouts.map((l) => `  ${l.id}: [${l.rows.map((k) => `[${k.join(",")}]`).join(",")}], // ${l.from}`),
  "};",
  "",
];
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/lib/brands/fw19f5/mchose-catalog.generated.ts");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out.join("\n"));
console.log(`${boards.length} boards, ${layouts.length} layouts, ${new Set(boards.flatMap((b) => b.ids.map((i) => i.join(":")))).size} ids -> ${dest}`);
