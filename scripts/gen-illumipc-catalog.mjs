// Writes src/lib/illumipc/catalog.generated.ts: the illumipc-driven keyboards SYNQ knows by product code (Redragon, Epomaker,
// Womier and the MAGIC-REFINER X68 HE), with their USB ids, names and key layouts.
//
// Run: node scripts/gen-illumipc-catalog.mjs <config directory>
//
// The directory is a read-only copy of illumipc.com's public configuration (https://www.illumipc.com/config/):
//   device.json            {"device": [{vid, pid, name, product, company, hasLight, ...}]}  the site's own device list
//   keys/<product>.json    {"type": "us"|"uk", "keys": [{index, name, code, hidCode, width, height, x, y}]}  one per product
// Only facts are kept (product codes, USB ids, names, matrix index / HID code / position of every key); the files
// themselves are not shipped. Pixel positions become key units (illumipc draws a key 38 px apart per unit, 35 px wide).
//
// Scope: the companies named below, plus the three X68 HE product codes the earlier X68 work knows. Everything else in
// device.json (about 190 more entries on 2E3C:C365, 0416:7372 and the gamepad-mode ids) is not listed here: a board SYNQ
// doesn't know opens read-only, as before.
//
// An illumipc layout file that does not exist falls back, in illumipc itself, to SI2828HEARGB's: the board is listed with
// that layout and `layoutFrom` says so.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/gen-illumipc-catalog.mjs <config directory with device.json and keys/>");
const devices = JSON.parse(fs.readFileSync(path.join(dir, "device.json"), "utf8")).device;

const COMPANIES = { fengrun_redragon: "Redragon", hongfeng_epomaker: "Epomaker", womier: "Womier" };
/** The X68 HE codes the earlier work identified (docs/keyboard-x68he/PROTOCOL.md section 1); they keep their programmatic layouts. */
const X68 = new Set(["AK1680UKX68ZAXHEARGB", "AK1680BRX68ZAXHEARGB", "AK1680GUKX68XYXCPHEARGB"]);
const FALLBACK = "SI2828HEARGB";
const PITCH = 38;

const num = (s) => parseInt(String(s), 16);
const r2 = (v) => Math.round(v * 100) / 100;
const layouts = [];
const layoutIds = new Map();
const readLayout = (product) => {
  const f = path.join(dir, "keys", `${product}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : null;
};
/** Layout id for a product's file (adds it once). */
function layoutOf(j) {
  const xs = j.keys.map((k) => Number(k.x));
  const ys = j.keys.map((k) => Number(k.y));
  const x0 = Math.min(...xs);
  const y0 = Math.min(...ys);
  const rows = j.keys
    .map((k) => {
      const hid = /^0x/i.test(k.hidCode) ? num(k.hidCode) : num(k.hidCode);
      const kind = k.code === "KeyFn" ? 1 : k.code === "RotaryKnob" ? 2 : /^CustomG\d$/.test(k.code) ? 3 : 0;
      if (kind === 0 && (hid < 0x04 || hid > 0xe7)) throw new Error(`${k.code}: HID ${k.hidCode} outside the keyboard page`);
      const w = r2((Number(k.width) + 3) / PITCH);
      const h = r2((Number(k.height) + 3) / PITCH);
      return [Number(k.index), kind === 0 ? hid : 0, r2((Number(k.x) - x0) / PITCH), r2((Number(k.y) - y0) / PITCH), w, h, kind, kind === 0 ? "" : (k.name ?? "")];
    })
    .filter((r) => !(r[1] === 0 && r[6] === 0));
  const id = JSON.stringify([j.type, rows]);
  if (!layoutIds.has(id)) {
    layoutIds.set(id, layouts.length);
    layouts.push({ type: j.type, rows });
  }
  return layoutIds.get(id);
};

const byProduct = new Map();
for (const d of devices) {
  const brand = COMPANIES[d.company] ?? (X68.has(d.product) ? "MAGIC-REFINER" : null);
  if (!brand) continue;
  const e = byProduct.get(d.product) ?? { product: d.product, brand, names: [], ids: [], light: true };
  if (d.name && !/[^\x20-\x7e]/.test(d.name) && !e.names.includes(d.name)) e.names.push(d.name);
  const id = [num(d.vid), num(d.pid)];
  if (!e.ids.some(([v, p]) => v === id[0] && p === id[1])) e.ids.push(id);
  e.light = e.light && d.hasLight !== false;
  byProduct.set(d.product, e);
}

const boards = [];
for (const e of [...byProduct.values()].sort((a, b) => a.brand.localeCompare(b.brand) || a.product.localeCompare(b.product))) {
  let layout = null;
  let layoutFrom = null;
  if (!X68.has(e.product)) {
    const own = readLayout(e.product);
    if (own) layout = layoutOf(own);
    else {
      const fb = readLayout(FALLBACK);
      if (!fb) throw new Error(`no layout for ${e.product} and no fallback ${FALLBACK}`);
      layout = layoutOf(fb);
      layoutFrom = FALLBACK;
    }
  }
  e.ids.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  boards.push({ product: e.product, brand: e.brand, name: e.names[0] ?? "", ids: e.ids, layout, layoutFrom, lighting: e.light });
}

const hex = (n) => `0x${n.toString(16).padStart(4, "0")}`;
const body = `// GENERATED by scripts/gen-illumipc-catalog.mjs from illumipc.com's public configuration (device.json and keys/<product>.json,
// read 2026-10-14). Do not edit. Facts only: product codes, USB ids, names, and where each key sits.
//
// ${boards.length} boards: ${[...new Set(boards.map((b) => b.brand))].map((b) => `${boards.filter((x) => x.brand === b).length} ${b}`).join(", ")}.
// A product code is what a keyboard reports to illumipc's configurator (command 0x0D); the USB id alone does not say which board it is.

/** [matrix index (row * 22 + col), HID usage, x, y, w, h (key units), kind (0 key, 1 Fn, 2 rotary knob, 3 custom G key), legend of a non-key]. */
export type IllumipcKeyRow = readonly [number, number, number, number, number, number, number, string];

export interface IllumipcLayout {
  /** illumipc's layout type: "us" (ANSI) or "uk" (ISO, ABNT); anything but "us" sends HID 0x32 for the key left of Enter in a SOCD pair. */
  type: string;
  keys: readonly IllumipcKeyRow[];
}

export interface IllumipcBoard {
  /** The product code the keyboard reports. */
  product: string;
  brand: string;
  /** The model name illumipc lists it under ("" when it lists none). */
  name: string;
  /** The USB ids it enumerates as (a gamepad-mode id is another personality of the same board). */
  ids: readonly (readonly [number, number])[];
  /** Index into ILLUMIPC_LAYOUTS, or null for the X68 HE family (src/lib/x68he-layout.ts builds those). */
  layout: number | null;
  /** The product whose layout file illumipc itself falls back to when it has none for this one. */
  layoutFrom: string | null;
  /** illumipc says the board has lighting. */
  lighting: boolean;
}

export const ILLUMIPC_BOARDS: readonly IllumipcBoard[] = [
${boards.map((b) => `  { product: ${JSON.stringify(b.product)}, brand: ${JSON.stringify(b.brand)}, name: ${JSON.stringify(b.name)}, ids: [${b.ids.map(([v, p]) => `[${hex(v)}, ${hex(p)}]`).join(", ")}], layout: ${b.layout}, layoutFrom: ${JSON.stringify(b.layoutFrom)}, lighting: ${b.lighting} },`).join("\n")}
];

export const ILLUMIPC_LAYOUTS: readonly IllumipcLayout[] = [
${layouts.map((l) => `  { type: ${JSON.stringify(l.type)}, keys: [${l.rows.map((r) => `[${r.slice(0, 7).join(",")},${JSON.stringify(r[7])}]`).join(",")}] },`).join("\n")}
];
`;
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/lib/illumipc/catalog.generated.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`${boards.length} boards, ${layouts.length} layouts -> ${out}`);
const ids = new Set(boards.flatMap((b) => b.ids.map(([v, p]) => `${hex(v)}:${hex(p)}`)));
console.log("USB ids:", [...ids].join(" "));
